package com.earth.domain.flare;

/**
 * 플레어를 만든 주체. 상세 화면이 "누가 남긴 플레어인지"를 보여 주는 데 쓴다.
 *
 * <p>작성자(author)만으로는 구분하지 않는다. 외부 데이터로 만든 플레어도 작성자 칸에는 시스템 계정이 들어가므로,
 * 작성자가 사람인지 시스템인지를 화면이 계정 정보로 추측하게 두지 않고 플레어 자체에 적어 둔다.
 */
public enum FlareOrigin {
    /** 사용자가 직접 남긴 플레어. */
    USER,
    /** 공공데이터 등 외부 API에서 받아 만든 플레어. 어디서 왔는지는 {@code Flare.source}. */
    API
}
