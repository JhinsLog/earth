package com.earth.domain.flare;

/**
 * 플레어를 만든 주체. 상세 화면이 "누가 남긴 플레어인지"를 보여 주는 데 쓴다.
 *
 * <p>작성자(author)만으로는 구분하지 않는다. 외부 데이터로 만든 플레어도 작성자 칸에는 시스템 계정이 들어가므로,
 * 작성자가 사람인지 시스템인지를 화면이 계정 정보로 추측하게 두지 않고 플레어 자체에 적어 둔다.
 */
public enum FlareOrigin {
    /** 사용자가 직접 남긴 플레어. */
    USER,
    /**
     * 공공 정보. 공공데이터로 받은 지금 벌어지는 상황(교통 돌발 등)이다. 그 자리의 사람들이 상황을 나누므로 채팅과 사실 확인을
     * 연다. 어디서 왔는지는 {@code Flare.source}(V15 전에는 축제·행사와 함께 API였다).
     */
    PUBLIC,
    /**
     * 축제·행사. 운영 주체가 공식 누리집에 공지한 일정(스키장 개장, 파리 행사 등)을 옮긴 것이다. 정해진 일정이라 "봤다·끝났다"를
     * 확인할 대상이 아니고, 채팅을 열면 홍보·후기 글이 쌓이기 쉬워 채팅과 사실 확인을 닫는다(D-19, D-22).
     */
    FESTIVAL
}
