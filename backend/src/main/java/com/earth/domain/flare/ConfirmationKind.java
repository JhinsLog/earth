package com.earth.domain.flare;

/**
 * 사실 확인의 종류. 한 사람은 한 플레어에 이 중 하나만 남긴다(V13).
 *
 * <p>{@link #SEEN}만 수명을 늘린다. 나머지 둘은 지금은 수만 보여 준다 — 몇 사람이 "끝났다"고 누르면 플레어를 내리는 식의
 * 규칙은 소수가 멀쩡한 플레어를 지울 수 있어, 쌓이는 수를 보고 따로 정한다(D-20).
 */
public enum ConfirmationKind {
    /** 나도 봤어요 — 지금도 그 상황이 있다. */
    SEEN,
    /** 끝났어요 — 상황이 정리됐다. */
    ENDED,
    /** 사실과 달라요 — 잘못된 정보 같다. */
    DISPUTED
}
