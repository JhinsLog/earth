-- 공감이 실제로 늘려준 수명을 기록한다. 취소할 때 정확히 그만큼만 되돌리기 위해서다.
--
-- 이전에는 취소가 공감 수만 줄이고 만료 시각은 그대로 두었다. 그러면 두 가지가 어긋난다.
--
-- 첫째, 취소 후 재공감으로 수명을 무한히 밀어올릴 수 있었다. 취소가 event_confirmations
-- 행을 삭제하므로 (event_id, user_id) 유니크 제약이 다시 통과하고, 재공감 때 연장이 또
-- 붙는다. 버튼을 반복해 누르면 한 사람이 혼자 상한(12시간)까지 채울 수 있었다.
-- "여러 명이 목격한 사건이 오래 남는다"는 정책이 한 사람에게 독점되는 셈이다.
--
-- 둘째, 공감이 0인데 기본 수명(30분)을 넘겨 살아 있는 별이 생겼다. "확인되지 않은 별은
-- 스스로 소멸한다"는 전제와 맞지 않는다.
--
-- 취소가 기여분을 정확히 회수하면 둘 다 해소되고, 한 사람의 순 기여가 구조적으로 1회분을
-- 넘지 못한다(+5분 -5분 +5분 … = 최대 +5분). 별도 장치가 필요 없어진다.
--
-- 5분을 그냥 빼면 안 되는 이유: 상한에 걸린 상태에서 공감하면 실제 연장이 5분보다 적거나
-- 0이다. 그때 5분을 빼면 자기가 준 것보다 많이 회수한다.
ALTER TABLE event_confirmations
    ADD COLUMN granted_seconds BIGINT NOT NULL DEFAULT 0;

-- 기존 행은 실제 기여분을 알 수 없다. 0으로 두면 취소해도 수명이 줄지 않아,
-- 지금까지의 동작(되돌리지 않음)이 그대로 유지된다. 새 공감부터 정확히 기록된다.
COMMENT ON COLUMN event_confirmations.granted_seconds IS
    '이 공감이 실제로 늘려준 수명(초). 취소 시 이만큼만 되돌린다. 0은 기록 이전에 생긴 공감.';
